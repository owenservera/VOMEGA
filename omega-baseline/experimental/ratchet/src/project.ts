// Projections: the board (Markdown for humans) and the evidence summary (JSON
// for machines) are GENERATED from graph + lock + probe. They are never edited
// by hand, so they cannot drift from the tests — the failure mode that produced
// 49 documentation-reconciliation commits out of 51.
//
// The run ledger is local, append-only and hash-chained (.local/, never
// committed): raw observations stay on the machine, sanitized summaries are
// committed. Harvested from the baseline's D-430/D-431 ledger discipline.
